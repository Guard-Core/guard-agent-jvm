      assertEquals("CLOSED", transport["circuit_breaker_state"])
      assertEquals(true, stats["last_status_push_ok"])
      assertEquals(
          mapOf("flush" to 0, "status" to 0, "rules" to 0),
          stats["loop_failures"] as Map<*, *>,
      )

      mock.statusCodeOverrideForTest(400)
      agent.reportStatus(AgentContext.NONE)
      stats = agent.agentStats()
