  private fun redisHost(): String? {
    val h = System.getenv("REDIS_HOST") ?: "127.0.0.1"
    return try {
      val client = io.lettuce.core.RedisClient.create("redis://$h:6379")
      val conn = client.connect()
      val pong = conn.sync().ping()
      conn.close()
      client.shutdown()
      if (pong == "PONG") h else null
    } catch (e: Exception) {
      null
    }
  }

  private fun deleteKeys(
      host: String,
      prefix: String,
  ) {
    val client = io.lettuce.core.RedisClient.create("redis://$host:6379")
    val conn = client.connect()
    val ks = conn.sync().keys("$prefix:*")
    if (ks.isNotEmpty()) conn.sync().del(*ks.toTypedArray())
    conn.close()
    client.shutdown()
  }

  @Test
  fun persistBacklogCapsAtBufferSizeAndWarnsOncePerEpisode() {
    val host = redisHost() ?: return
    val mock = MockIngest()
    val prefix = "guardagent-cap-" + System.nanoTime()
    val logger = CapturingLogger()
    val gate = CountDownLatch(1)
    val entered = CountDownLatch(3)
    val agent =
        newTestAgent(tempDirFor("persist-cap"), mock, AgentOptions().withLogger(logger)) { c ->
          c.bufferSize = 3
          c.redis = RedisConfig("redis://$host:6379", prefix, Duration.ofMinutes(1))
        }
    agent.persist!!.commandFaultInjector = { name ->
      if (name == "set") {
        entered.countDown()
        gate.await(30, TimeUnit.SECONDS)
      }
      null
    }
    try {
      for (i in 1..3) agent.sendEvent(testEvent(i))
      assertTrue(entered.await(15, TimeUnit.SECONDS), "three writes must be in flight")
      for (i in 4..6) agent.sendEvent(testEvent(i))
      assertEquals(3L, agent.stats().redisPersistFailures, "past the cap the writes are skipped")
      assertEquals(1, logger.count("persist backlog at buffer_size=3"), "one warning per episode")
      gate.countDown()
      agent.awaitPersists()
      waitUntil(Duration.ofSeconds(15), "backlog drained") {
        synchronized(agent.mutex) { agent.persistInflight == 0 }
      }
      // A new backlog episode warns again.
      val gate2 = CountDownLatch(1)
      val entered2 = CountDownLatch(3)
      agent.persist!!.commandFaultInjector = { name ->
        if (name == "set") {
          entered2.countDown()
          gate2.await(30, TimeUnit.SECONDS)
        }
        null
      }
      for (i in 7..9) agent.sendEvent(testEvent(i))
      assertTrue(entered2.await(15, TimeUnit.SECONDS))
      agent.sendEvent(testEvent(10))
      assertEquals(2, logger.count("persist backlog at buffer_size=3"))
      gate2.countDown()
    } finally {
      gate.countDown()
      agent.stop()
      deleteKeys(host, prefix)
      mock.close()
    }
  }

