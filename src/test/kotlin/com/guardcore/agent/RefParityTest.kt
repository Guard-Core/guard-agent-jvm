  @Test
  fun cancelledContextIsNotABreakerFailure() {
    val mock = MockIngest()
    try {
      val tr = Transport(config(mock.url), "install", null, quietLogger())
      val ctx = AgentContext.withCancel()
      ctx.cancel()
      assertTrue(tr.sendBatch(ctx, EVENTS_PATH, "{}".toByteArray()).second is ContextDone)
      assertTrue(tr.fetchDynamicRules(ctx).second is ContextDone)
      assertEquals(0, tr.breaker.failureCount())
      assertEquals(0L, tr.requestsFailed.get())

      // A context cancelled while the request is in flight is not a fault either.
      val inFlight = AgentContext.withCancel()
      val doer = HttpDoer { _, _, _ ->
        inFlight.cancel()
        throw inFlight.err()
      }
      val tr2 = Transport(config(mock.url), "install", doer, quietLogger())
      assertTrue(tr2.sendBatch(inFlight, EVENTS_PATH, "{}".toByteArray()).second is ContextDone)
      assertEquals(0, tr2.breaker.failureCount())
    } finally {
      mock.close()
    }
  }

