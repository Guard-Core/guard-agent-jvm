  @Test
  fun responseSemanticsMatchReferenceVectors() {
    val vectors = parseJson(resource("response_vectors.json"), useNumber = false) as List<*>
    assertTrue(vectors.isNotEmpty())
    val failures = mutableListOf<String>()
    for (raw in vectors) {
      val v = raw as Map<*, *>
      val status = (v["status"] as Number).toInt()
      val body = v["body"] as String
      val headers = v["headers"] as Map<*, *>
      val requests = AtomicInteger()
      val server = HttpServer.create(InetSocketAddress("127.0.0.1", 0), 0)
      server.createContext("/") { exchange ->
        requests.incrementAndGet()
        exchange.requestBody.readBytes()
        for ((k, value) in headers) exchange.responseHeaders.add(k.toString(), value.toString())
        val bytes = body.toByteArray()
        exchange.sendResponseHeaders(status, if (bytes.isEmpty()) -1 else bytes.size.toLong())
        if (bytes.isNotEmpty()) exchange.responseBody.write(bytes)
        exchange.close()
      }
      server.start()
      val tr =
          Transport(
              config("http://127.0.0.1:" + server.address.port),
              "install",
              null,
              quietLogger(),
          )
      val kind = v["kind"] as String
      val confirmed =
          when (kind) {
            "events" ->
                sendOutcomeConfirms(tr.sendEvents(AgentContext.NONE, listOf(testEvent(1))).first)
            "status" -> {
              val payload = AgentStatusPayload()
              payload.timestamp = Instant.now()
              payload.status = AgentStatusValues.HEALTHY
              tr.sendStatus(AgentContext.NONE, payload).first == SendOutcome.ACCEPTED
            }
            else -> tr.fetchDynamicRules(AgentContext.NONE).first != null
          }
      server.stop(0)
      val wantConfirmed = v["confirmed"] as Boolean
      val wantRequests = (v["requests"] as Number).toInt()
      val wantBreaker = (v["breaker_failures"] as Number).toInt()
      if (
          confirmed != wantConfirmed ||
              requests.get() != wantRequests ||
              tr.breaker.failureCount() != wantBreaker
      ) {
        failures.add(
            "$kind $status \"$body\": got confirmed=$confirmed requests=${requests.get()} " +
                "breaker=${tr.breaker.failureCount()}, reference confirmed=$wantConfirmed " +
                "requests=$wantRequests breaker=$wantBreaker",
        )
      }
    }
    if (failures.isNotEmpty()) fail(failures.joinToString("\n"))
  }

  private fun assertShape(
      name: String,
      want: Map<*, *>,
      got: Map<*, *>,
  ) {
    for ((key, kind) in want) {
      if (kind == "NoneType") continue
      val value = got[key]
      assertTrue(got.containsKey(key), "$name: reference key $key missing")
      val ok =
          when (kind) {
            "str" -> value is String
            "list" -> value is List<*>
            "dict" -> value is Map<*, *>
            "bool" -> value is Boolean
            else -> value is Number
          }
      assertTrue(ok, "$name.$key: reference $kind, got $value")
    }
    for (key in got.keys) {
      assertTrue(want.containsKey(key), "$name: key $key is not in the reference shape")
    }
  }

  @Test
  fun wireShapeMatchesReference() {
    val shapes = parseJson(resource("wire_shape.json"), useNumber = false) as Map<*, *>
    val tr =
        Transport(defaultConfig().apply { apiKey = "test-api-key-123" }, "i", null, quietLogger())
    // Events and metrics arrive without metadata or tags: the null cases.
    val batch = EventBatch()
    batch.projectId = "p"
    batch.batchId = "b"
    batch.createdAt = Instant.now()
    batch.events = listOf(SecurityEvent(Instant.now(), "x", "k"))
    batch.metrics = listOf(SecurityMetric(Instant.now(), MetricTypes.REQUEST_COUNT))
    val parsed = parseJson(tr.marshalBatch(batch), useNumber = false) as Map<*, *>
    assertShape("batch", shapes["batch"] as Map<*, *>, parsed)
    assertShape(
        "event",
        shapes["event"] as Map<*, *>,
        (parsed["events"] as List<*>)[0] as Map<*, *>,
    )
    assertShape(
        "metric",
        shapes["metric"] as Map<*, *>,
        (parsed["metrics"] as List<*>)[0] as Map<*, *>,
    )
    val status = AgentStatusPayload()
    status.timestamp = Instant.now()
    status.status = AgentStatusValues.HEALTHY
    assertShape(
        "status",
        shapes["status"] as Map<*, *>,
        parseJson(goJson(status), useNumber = false) as Map<*, *>,
    )

    // An empty batch still carries both lists.
    val empty = String(tr.marshalBatch(EventBatch()), Charsets.UTF_8)
    assertTrue(empty.contains("\"events\":[]") && empty.contains("\"metrics\":[]"), empty)
  }

  @Test
  fun encrypted413SplitsAndReencryptsEachHalf() {
    val mock = MockIngest()
    try {
      mock.setMaxBody(2200)
      val cfg = config(mock.url).apply { retryAttempts = 0 }
      val tr = Transport(cfg, "install", null, quietLogger())
      tr.encryptor = PayloadEncryptor.create(encryptionKey())
      val pad = "x".repeat(600)
      val events =
          listOf(testEvent(1, pad), testEvent(2, pad), testEvent(3, pad), testEvent(4, pad))
      val (outcome, err) = tr.sendEvents(AgentContext.NONE, events)
      assertEquals(SendOutcome.ACCEPTED, outcome, "an encrypted 413 must split and confirm: $err")
      val calls = mock.callsTo(ENCRYPTED_PATH)
      val oversized = calls.count { it.response == 413 }
      val accepted = calls.count { it.response != 413 }
      assertTrue(oversized >= 1 && accepted >= 2, "oversized=$oversized accepted=$accepted")

      val metrics = listOf(testMetric(1), testMetric(2))
      for (m in metrics) m.tags = mapOf("pad" to "y".repeat(1200))
      val before = mock.callsTo(ENCRYPTED_PATH).size
      val (mOutcome, _) = tr.sendMetrics(AgentContext.NONE, metrics)
      assertEquals(SendOutcome.ACCEPTED, mOutcome)
      assertTrue(mock.callsTo(ENCRYPTED_PATH).size - before >= 3, "metrics must split too")
    } finally {
      mock.close()
    }
  }

