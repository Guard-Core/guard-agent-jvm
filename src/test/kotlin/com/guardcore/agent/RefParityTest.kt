  @Test
  fun persistKeysCarryTheWallClockStamp() {
    val persistence =
        Persistence("redis://127.0.0.1:6379", "p", Duration.ofMinutes(1), quietLogger())
    try {
      val before = System.currentTimeMillis() * 1_000_000L
      val first = persistence.shortKey("event")
      val second = persistence.shortKey("event")
      val after = System.currentTimeMillis() * 1_000_000L + 1_000_000L
      val stamps = listOf(first, second).map { it.split("_")[1].toLong() }
      assertTrue(
          stamps[0] >= before - 1_000_000L && stamps[1] <= after,
          "stamps $stamps outside the wall clock window",
      )
      assertTrue(stamps[1] > stamps[0], "keys minted in order must sort in order")
    } finally {
      persistence.close()
    }
  }
